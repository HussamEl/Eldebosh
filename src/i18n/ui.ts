export function t(lang: Lang) {
  return (key: keyof (typeof ui)['sv']): string => {
    const value = ui[lang][key] ?? ui[DEFAULT_LANG][key];
    // Utan detta renderas en saknad nyckel som strängen "undefined" rakt ut i
    // sidan — det var precis vad 'nav.home' gjorde i logotypens aria-label.
    if (typeof value !== 'string') {
      throw new Error(`i18n: saknad nyckel "${String(key)}" för språket "${lang}"`);
    }
    return value;
  };
}

export function isLang(value: string): value is Lang {
  return (LANGS as readonly string[]).includes(value);
}
