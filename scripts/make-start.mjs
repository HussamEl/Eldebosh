const STAMP = /^>\s*\*\*Version:\*\*\s*`(v[\d.]+)`\s*·\s*(\d{4}-\d{2}-\d{2})/m;
const versions = ['INSTRUCTIONS', 'CONTEXT', 'BRIEFING'].map((n) => {
  const m = read(`docs/project/${n}.md`).match(STAMP);
  return { name: n, version: m ? m[1] : '?', date: m ? m[2] : '?' };
});

/* ---------- الرقم التالي في السجل ---------- */
const log = read('docs/project/LOG.md');
const from = log.lastIndexOf('<!-- COUNTER-RESET ');
const to = log.indexOf('<!-- COUNTER-RESET-END', from + 1);
const live = from === -1 ? log : log.slice(from, to === -1 ? undefined : to);
const rows = live.match(/^\|\s*EB-(\d{3})\s*\|/gm) ?? [];
const nextNum = rows.length
  ? Math.max(...rows.map((r) => Number(r.match(/EB-(\d{3})/)[1]))) + 1
  : 1;
const next = `EB-${String(nextNum).padStart(3, '0')}`;

/* ---------- الفئات: من ملفاتها ---------- */
import YAML from 'yaml';
import { readdirSync } from 'node:fs';
const catDir = join(ROOT, 'src/data/categories');
const cats = readdirSync(catDir)
  .filter((f) => /\.ya?ml$/.test(f))
  .map((f) => YAML.parse(readFileSync(join(catDir, f), 'utf8')))
  .sort((a, b) => (a.order ?? 99) - (b.order ?? 99));

const catBlock = cats
  .map((c) => `${c.id}\n    ${(c.subcategories ?? []).map((s) => s.id).join(' · ')}`)
  .join('\n\n');

/* ---------- الرمز الحرّ التالي ---------- */
const prodDir = join(ROOT, 'src/data/products/sv');
const codes = readdirSync(prodDir)
  .filter((f) => /\.ya?ml$/.test(f))
  .map((f) => (readFileSync(join(prodDir, f), 'utf8').match(/^code:\s*P-(\d{2})/m) ?? [])[1])
  .filter(Boolean)
  .map(Number);
